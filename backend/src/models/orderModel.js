/**
 * Get order statistics for a user
 */
async function getUserOrderStats(userId) {
  const query = `
    SELECT 
      COUNT(*) as total_orders,
      COUNT(*) FILTER (WHERE order_status = 'pending') as pending_orders,
      COUNT(*) FILTER (WHERE order_status = 'confirmed') as confirmed_orders,
      COUNT(*) FILTER (WHERE order_status = 'delivered') as delivered_orders,
      COUNT(*) FILTER (WHERE order_status = 'completed') as completed_orders,
      COUNT(*) FILTER (WHERE order_status = 'cancelled') as cancelled_orders,
      COALESCE(SUM(total_amount) FILTER (WHERE order_status != 'cancelled'), 0) as total_spent
    FROM orders
    WHERE user_id = $1;
  `;
  
  const result = await pool.query(query, [userId]);
  
  return {
    totalOrders: parseInt(result.rows[0].total_orders, 10),
    pendingOrders: parseInt(result.rows[0].pending_orders, 10),
    confirmedOrders: parseInt(result.rows[0].confirmed_orders, 10),
    deliveredOrders: parseInt(result.rows[0].delivered_orders, 10),
    completedOrders: parseInt(result.rows[0].completed_orders, 10),
    cancelledOrders: parseInt(result.rows[0].cancelled_orders, 10),
    totalSpent: parseFloat(result.rows[0].total_spent)
  };
}

/**
 * Get order items by order ID
 */
async function getOrderItems(orderId) {
  const query = 'SELECT * FROM order_items WHERE order_id = $1 ORDER BY created_at;';
  const result = await pool.query(query, [orderId]);
  
  return result.rows.map(mapOrderItemRow);
}

