const pool = require('../config/db');

/**
 * Order Data Access Layer
 * Handles order and order_items database operations
 */

/**
 * Map database row to order object with camelCase naming
 */
function mapOrderRow(row) {
  if (!row) return null;
  
  return {
    id: row.id,
    userId: row.user_id,
    firebaseUid: row.firebase_uid,
    orderNumber: row.order_number,
    totalAmount: parseFloat(row.total_amount),
    paymentMethod: row.payment_method,
    paymentStatus: row.payment_status,
    orderStatus: row.order_status,
    deliveryAddress: row.delivery_address,
    notes: row.notes,
    createdAt: row.created_at,
    updatedAt: row.updated_at
  };
}

/**
 * Map database row to order item object
 */
function mapOrderItemRow(row) {
  if (!row) return null;
  
  return {
    id: row.id,
    orderId: row.order_id,
    productId: row.product_id,
    productName: row.product_name,
    productSku: row.product_sku,
    quantity: parseInt(row.quantity, 10),
    unitPrice: parseFloat(row.unit_price),
    totalPrice: parseFloat(row.total_price),
    createdAt: row.created_at
  };
}

/**
 * Create order with order items in a transaction
 * Returns the created order with order items
 */
async function createOrder(orderData, orderItems, client = null) {
  const shouldManageTransaction = !client;
  const dbClient = client || await pool.connect();
  
  try {
    if (shouldManageTransaction) {
      await dbClient.query('BEGIN');
    }
    
    // Insert order (order_number will be auto-generated by trigger)
    const orderQuery = `
      INSERT INTO orders (
        user_id, firebase_uid, total_amount, payment_method, 
        payment_status, order_status, delivery_address, notes
      )
      VALUES ($1, $2, $3, $4, $5, $6, $7, $8)
      RETURNING *;
    `;
    
    const orderValues = [
      orderData.userId,
      orderData.firebaseUid,
      orderData.totalAmount,
      orderData.paymentMethod || 'COD',
      orderData.paymentStatus || 'pending',
      orderData.orderStatus || 'pending',
      JSON.stringify(orderData.deliveryAddress),
      orderData.notes || null
    ];
    
    const orderResult = await dbClient.query(orderQuery, orderValues);
    const order = mapOrderRow(orderResult.rows[0]);
    
    // Insert order items
    const itemsToInsert = [];
    for (const item of orderItems) {
      const itemQuery = `
        INSERT INTO order_items (
          order_id, product_id, product_name, product_sku,
          quantity, unit_price, total_price
        )
        VALUES ($1, $2, $3, $4, $5, $6, $7)
        RETURNING *;
      `;
      
      const itemValues = [
        order.id,
        item.productId,
        item.productName,
        item.productSku,
        item.quantity,
        item.unitPrice,
        item.totalPrice
      ];
      
      const itemResult = await dbClient.query(itemQuery, itemValues);
      itemsToInsert.push(mapOrderItemRow(itemResult.rows[0]));
    }
    
    if (shouldManageTransaction) {
      await dbClient.query('COMMIT');
    }
    
    return {
      ...order,
      items: itemsToInsert
    };
  } catch (error) {
    if (shouldManageTransaction) {
      await dbClient.query('ROLLBACK');
    }
    throw error;
  } finally {
    if (shouldManageTransaction) {
      dbClient.release();
    }
  }
}

/**
 * Find order by ID with order items
 */
async function findOrderById(orderId) {
  const orderQuery = 'SELECT * FROM orders WHERE id = $1;';
  const orderResult = await pool.query(orderQuery, [orderId]);
  
  if (orderResult.rows.length === 0) {
    return null;
  }
  
  const order = mapOrderRow(orderResult.rows[0]);
  
  // Fetch order items
  const itemsQuery = 'SELECT * FROM order_items WHERE order_id = $1 ORDER BY created_at;';
  const itemsResult = await pool.query(itemsQuery, [orderId]);
  
  order.items = itemsResult.rows.map(mapOrderItemRow);
  
  return order;
}

