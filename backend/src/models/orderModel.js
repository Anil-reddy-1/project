/**
 * Find orders by user ID with pagination and filters
 */
async function findOrdersByUserId(userId, { page = 1, limit = 20, status, dateFrom, dateTo } = {}) {
  const offset = (page - 1) * limit;
  const whereClauses = ['user_id = $1'];
  const queryParams = [userId];
  
  if (status) {
    queryParams.push(status);
    whereClauses.push(`order_status = $${queryParams.length}`);
  }
  
  if (dateFrom) {
    queryParams.push(new Date(dateFrom));
    whereClauses.push(`created_at >= $${queryParams.length}`);
  }
  
  if (dateTo) {
    queryParams.push(new Date(dateTo));
    whereClauses.push(`created_at <= $${queryParams.length}`);
  }
  
  const whereString = whereClauses.join(' AND ');
  
  // Count total
  const countQuery = `SELECT COUNT(*) FROM orders WHERE ${whereString};`;
  const countResult = await pool.query(countQuery, queryParams);
  const total = parseInt(countResult.rows[0].count, 10);
  
  // Fetch orders
  const dataParams = [...queryParams, limit, offset];
  const dataQuery = `
    SELECT * FROM orders
    WHERE ${whereString}
    ORDER BY created_at DESC
    LIMIT $${dataParams.length - 1} OFFSET $${dataParams.length};
  `;
  const dataResult = await pool.query(dataQuery, dataParams);
  
  const orders = dataResult.rows.map(mapOrderRow);
  
  // Fetch items for each order
  for (const order of orders) {
    const itemsQuery = 'SELECT * FROM order_items WHERE order_id = $1 ORDER BY created_at;';
    const itemsResult = await pool.query(itemsQuery, [order.id]);
    order.items = itemsResult.rows.map(mapOrderItemRow);
  }
  
  return {
    orders,
    total,
    page,
    limit
  };
}

/**
 * Find all orders with pagination and filters (admin view)
 */
async function findAllOrders({ page = 1, limit = 20, status, paymentStatus, dateFrom, dateTo, search } = {}) {
  const offset = (page - 1) * limit;
  const whereClauses = [];
  const queryParams = [];
  
  if (status) {
    queryParams.push(status);
    whereClauses.push(`order_status = $${queryParams.length}`);
  }
  
  if (paymentStatus) {
    queryParams.push(paymentStatus);
    whereClauses.push(`payment_status = $${queryParams.length}`);
  }
  
  if (dateFrom) {
    queryParams.push(new Date(dateFrom));
    whereClauses.push(`created_at >= $${queryParams.length}`);
  }
  
  if (dateTo) {
    queryParams.push(new Date(dateTo));
    whereClauses.push(`created_at <= $${queryParams.length}`);
  }
  
  if (search) {
    queryParams.push(`%${search}%`);
    whereClauses.push(`(order_number ILIKE $${queryParams.length} OR firebase_uid ILIKE $${queryParams.length})`);
  }
  
  const whereString = whereClauses.length > 0 ? `WHERE ${whereClauses.join(' AND ')}` : '';
  
  // Count total
  const countQuery = `SELECT COUNT(*) FROM orders ${whereString};`;
  const countResult = await pool.query(countQuery, queryParams);
  const total = parseInt(countResult.rows[0].count, 10);
  
  // Fetch orders
  const dataParams = [...queryParams, limit, offset];
  const dataQuery = `
    SELECT o.*, u.name as customer_name, u.email as customer_email
    FROM orders o
    LEFT JOIN users u ON o.user_id = u.id
    ${whereString}
    ORDER BY o.created_at DESC
    LIMIT $${dataParams.length - 1} OFFSET $${dataParams.length};
  `;
  const dataResult = await pool.query(dataQuery, dataParams);
  
  const orders = dataResult.rows.map(row => ({
    ...mapOrderRow(row),
    customerName: row.customer_name,
    customerEmail: row.customer_email
  }));
  
  // Fetch items for each order
  for (const order of orders) {
    const itemsQuery = 'SELECT * FROM order_items WHERE order_id = $1 ORDER BY created_at;';
    const itemsResult = await pool.query(itemsQuery, [order.id]);
    order.items = itemsResult.rows.map(mapOrderItemRow);
  }
  
  return {
    orders,
    total,
    page,
    limit
  };
}

/**
 * Update order status
 */
async function updateOrderStatus(orderId, status, notes = null) {
  const query = `
    UPDATE orders
    SET order_status = $1, notes = COALESCE($2, notes), updated_at = CURRENT_TIMESTAMP
    WHERE id = $3
    RETURNING *;
  `;
  
  const result = await pool.query(query, [status, notes, orderId]);
  
  if (result.rows.length === 0) {
    return null;
  }
  
  return mapOrderRow(result.rows[0]);
}

